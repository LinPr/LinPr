#!/usr/bin/env python3
"""Refresh the profile stat cards and re-tint them to the Itachi crimson theme.

The cards are generated by github-profile-summary-cards, downloaded as SVG, and
committed to assets/cards so the README never depends on a third-party service
at render time. If the upstream service is unavailable this script exits with a
non-zero status and the previously committed cards are kept.
"""

from __future__ import annotations

import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

USER = "LinPr"
THEME = "github_dark"
BASE = "https://github-profile-summary-cards.vercel.app/api/cards"

CARDS = {
    "stats": "stats",
    "most-commit-language": "languages",
    "profile-details": "overview",
}

# Blue/green -> Akatsuki crimson, muted text -> GitHub muted text.
COLORS = {
    "#0366d6": "#E23B3B",  # titles
    "#40c463": "#E23B3B",  # contribution graph
    "#77909c": "#9AA4B2",  # body text
    "#2e343b": "#30363D",  # card border
}

OUT_DIR = Path(__file__).resolve().parent.parent / "assets" / "cards"


def fetch(card: str) -> str:
    url = f"{BASE}/{card}?username={USER}&theme={THEME}"
    request = urllib.request.Request(
        url,
        headers={"User-Agent": f"{USER}-profile-card-refresh"},
    )
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            svg = response.read().decode("utf-8")
    except (urllib.error.URLError, TimeoutError) as exc:
        raise SystemExit(f"error: could not fetch {url}: {exc}") from exc

    if not svg.lstrip().startswith("<svg"):
        raise SystemExit(f"error: {url} did not return an SVG")

    for old, new in COLORS.items():
        svg = re.sub(re.escape(old), new, svg, flags=re.IGNORECASE)
    return svg


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    changed = False

    for card, filename in CARDS.items():
        path = OUT_DIR / f"{filename}.svg"
        svg = fetch(card)
        if path.exists() and path.read_text(encoding="utf-8") == svg:
            print(f"unchanged: {path.relative_to(OUT_DIR.parent.parent)}")
            continue
        path.write_text(svg, encoding="utf-8")
        changed = True
        print(f"updated:   {path.relative_to(OUT_DIR.parent.parent)}")

    if not changed:
        print("all cards are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
